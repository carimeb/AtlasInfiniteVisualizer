// ─── TAB 4 — HORIZONTAL READ SCALING ─────────────────────────────────────────
// Up to 5 read-only + analytics nodes on top of the 2 electable nodes (7 max) [D6].
// New nodes read from the storage layer and serve reads in minutes, no initial sync [D2, D6].

const XP = {};
let hsSeq = { READ_ONLY: 0, ANALYTICS: 0 };
const HS_BI_RATE = 6;   // k reads/s generated by the analytics app (illustrative)

function hsAdd(type) {
  if (S.extra.length >= MAX_EXTRA) {
    log('WARN', 'ATLAS', tx('Limit reached: up to 5 read-only + analytics nodes combined (7 nodes max)', 'Limite atingido: até 5 nós read-only + analytics somados (máx. 7 nós)'));
    return;
  }
  const pref = [2, 0, 1, 2, 0][S.extra.length];
  const az = [pref, 0, 1, 2].find(a => !S.ha.azDown[a]);
  if (az === undefined) { log('ERROR', 'ATLAS', tx('No healthy zone to place the node', 'Nenhuma zona saudável para posicionar o nó')); return; }
  const id = (type === 'READ_ONLY' ? 'ro-' : 'an-') + (++hsSeq[type]);
  const n = { id, type, az, state: 'PROVISIONING' };
  S.extra.push(n);
  log('INFO', 'ATLAS', tx(`Adding ${type === 'READ_ONLY' ? 'read-only' : 'analytics'} node ${id} in ${AZ_NAMES[az]} — it reads from the storage layer, no initial sync`, `Adicionando nó ${type === 'READ_ONLY' ? 'read-only' : 'analytics'} ${id} em ${AZ_NAMES[az]} — lê da camada de storage, sem initial sync`));
  syncAll();
  setTimeout(() => {
    if (!S.extra.includes(n) || n.state !== 'PROVISIONING') return;
    n.state = S.ha.azDown[n.az] ? 'DOWN' : 'UP';
    log('SUCCESS', id.toUpperCase(), tx(`${id} serving reads — attached to storage, 0 bytes copied`, `${id} atendendo leituras — conectado ao storage, 0 bytes copiados`));
    syncAll();
  }, 2200);
}

function hsRemove() {
  const n = S.extra.pop();
  if (!n) return;
  log('INFO', 'ATLAS', tx(`Removed ${n.id}; its reads are re-routed`, `${n.id} removido; suas leituras são redirecionadas`));
  syncAll();
}

// Server selection per the driver read-preference rules (tags filter secondaries)
function hsRoutes() {
  const up = [...S.ha.nodes, ...S.extra].filter(n => n.state === 'UP');
  const prim = up.find(n => n.role === 'PRIMARY');
  const secAll = up.filter(n => n.role !== 'PRIMARY');
  const tagOf = n => n.type || 'ELECTABLE';
  const tg = S.hs.tags;
  const secs = tg === 'none' ? secAll : secAll.filter(n => tagOf(n) === tg);
  const primMatches = prim && (tg === 'none' || tg === 'ELECTABLE');
  let ops = [], opsErr = '';
  if (S.rp === 'primary' && tg !== 'none') opsErr = tx('readPreferenceTags can\'t be combined with mode "primary"', 'readPreferenceTags não pode ser combinado com o modo "primary"');
  else switch (S.rp) {
    case 'primary': ops = prim ? [prim] : []; break;
    case 'primaryPreferred': ops = prim ? [prim] : secs; break;
    case 'secondary': ops = secs; break;
    case 'secondaryPreferred': ops = secs.length ? secs : (prim ? [prim] : []); break;
    case 'nearest': ops = [...(primMatches ? [prim] : []), ...secs]; break;
  }
  if (!ops.length && !opsErr) opsErr = tx('no eligible node — server selection times out', 'nenhum nó elegível — a seleção de servidor dá timeout');
  const bi = S.hs.bi ? up.filter(n => n.type === 'ANALYTICS') : [];
  const biErr = S.hs.bi && !bi.length ? tx('no node tagged ANALYTICS — server selection times out', 'nenhum nó com tag ANALYTICS — a seleção de servidor dá timeout') : '';
  return { ops, opsErr, bi, biErr };
}

function hsLoads() {
  const r = hsRoutes();
  const opsRate = S.hs.rps * 2;
  const loads = {};
  [...S.ha.nodes, ...S.extra].forEach(n => { loads[n.id] = { ops: 0, bi: 0 }; });
  r.ops.forEach(n => { loads[n.id].ops = opsRate / r.ops.length; });
  r.bi.forEach(n => { loads[n.id].bi = HS_BI_RATE / r.bi.length; });
  return { r, loads, opsRate };
}

