// Continuous traffic pulses while the tab is visible
function hsPulse() {
  if (S.tab !== 'hs') return;
  const r = hsRoutes();
  if (r.ops.length) {
    const nd = r.ops[Math.floor(Math.random() * r.ops.length)];
    const [x, y] = XP.nodes[nd.id] || [];
    if (x) fly('hs-svg', [[230, 44], [230, 80], [x, y - 60], [x, y - 26]], 900, C.slate, 4);
  }
  if (r.bi.length && Math.random() < 0.6) {
    const nd = r.bi[Math.floor(Math.random() * r.bi.length)];
    const [x, y] = XP.nodes[nd.id] || [];
    if (x) fly('hs-svg', [[560, 44], [560, 80], [x, y - 60], [x, y - 26]], 1100, C.spring, 4);
  }
}
